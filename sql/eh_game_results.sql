-- ===== 小游戏战绩 (斗地主/掼蛋) 2026-08-14 =====
-- 策略「全记」: 每局都存一行, 含 seed + transition log(moves) 供服务端复核与回看。
-- 单人 vs AI 阶段由客户端写入(引擎权威跑在浏览器);真人房阶段改由 Edge 权威写入。
-- 未来若做统一积分系统, 从这张表聚合即可, 无需回填。

create table if not exists public.eh_game_results (
  id bigint generated by default as identity primary key,
  game text not null,                        -- 'doudizhu' | 'guandan'
  room_id uuid,                              -- 所属房间(可空: 大厅试玩)
  room_name text,
  seed bigint,                               -- 洗牌种子: 与 moves 一起可完整复现/复核
  players jsonb not null,                    -- [{seat,name,uid,is_ai,role}]
  winner_seats int[] not null,
  loser_seats int[] not null,
  landlord_seat int,
  landlord_won boolean,
  score int,                                 -- 本局基础得分(底分×倍数)
  final_multiplier int,
  spring boolean default false,
  bombs int default 0,
  my_uid uuid not null,                      -- 记录发起者(当前只记"我"的视角一行)
  my_seat int,
  my_delta int,                              -- 我这局的加减分
  my_won boolean,
  is_ai boolean[],                           -- 各席是否 AI(公平性审计: 是否人机局)
  is_ranked boolean default false,           -- 是否计入排位(匿名/AI局=false)
  moves jsonb,                               -- transition log: 回看数据源
  ended_at timestamptz default now(),
  created_at timestamptz default now()
);
create index if not exists eh_game_results_my_idx on public.eh_game_results(my_uid, created_at desc);
create index if not exists eh_game_results_room_idx on public.eh_game_results(room_id, created_at desc);

alter table public.eh_game_results enable row level security;

-- 只能写自己视角的行(my_uid=自己), 读也只读自己的战绩(后续要做房间战绩榜再放开)。
drop policy if exists eh_game_results_insert on public.eh_game_results;
create policy eh_game_results_insert on public.eh_game_results
  for insert to public
  with check (my_uid = auth.uid());

drop policy if exists eh_game_results_select on public.eh_game_results;
create policy eh_game_results_select on public.eh_game_results
  for select to public
  using (my_uid = auth.uid());

