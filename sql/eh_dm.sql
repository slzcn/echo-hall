-- 收件箱: 一次拿回所有会话线 + 对方资料 + 未读数 + 最后一条(免前端 N 次查)
create or replace function public.eh_dm_inbox()
returns table(thread_id uuid, other_uid uuid, other_name text, other_emoji text, other_color text,
              last_text text, last_msg_at timestamptz, last_from uuid, unread int)
language sql
security definer
set search_path to 'public'
as $$
  select t.id,
    case when t.user_a = auth.uid() then t.user_b else t.user_a end as other_uid,
    u.name, u.emoji, u.color,
    t.last_text, t.last_msg_at, t.last_from,
    (select count(*)::int from public.eh_dm_messages m
       where m.thread_id = t.id and m.from_uid <> auth.uid() and m.read_at is null) as unread
  from public.eh_dm_threads t
  join public.eh_users u
    on u.id = (case when t.user_a = auth.uid() then t.user_b else t.user_a end)
  where t.user_a = auth.uid() or t.user_b = auth.uid()
  order by t.last_msg_at desc nulls last
$$;
grant execute on function public.eh_dm_inbox() to public;
